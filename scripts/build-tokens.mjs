import { readFileSync, writeFileSync, existsSync } from "node:fs";
import { resolve } from "node:path";
import assert from "node:assert/strict";

const root = resolve(import.meta.dirname, "..");
const tokens = JSON.parse(readFileSync(resolve(root, "packages/ui/src/tokens.json"), "utf8"));
const name = key => key.replace(/[A-Z]/g, char => "-" + char.toLowerCase()).replaceAll(".", "-");
const colors = theme => Object.entries(tokens.themes[theme]).map(([key, value]) => "  --" + name(key) + ": " + value + ";").join("\n");
const common = [
  ...tokens.spacing.map(value => "  --space-" + value + ": " + value + "px;"),
  ...Object.entries(tokens.radius).map(([key, value]) => "  --radius-" + key + ": " + value + "px;"),
  ...Object.entries(tokens.typography).flatMap(([key, value]) => [
    "  --font-" + key + "-size: " + value.size + "px;",
    "  --font-" + key + "-line: " + value.lineHeight + "px;",
    "  --font-" + key + "-weight: " + value.weight + ";"
  ]),
  '  --font-family: system-ui, -apple-system, BlinkMacSystemFont, "Apple SD Gothic Neo", "Noto Sans KR", sans-serif;'
].join("\n");
const css = [
  "/* Generated by scripts/build-tokens.mjs. Edit tokens.json. */",
  ":root {\n  color-scheme: light;\n" + common + "\n" + colors("light") + "\n}",
  ':root[data-theme="dark"] {\n  color-scheme: dark;\n' + colors("dark") + "\n}",
  '@media (prefers-color-scheme: dark) {\n  :root:not([data-theme="light"]):not([data-theme="dark"]) {\n    color-scheme: dark;\n' + colors("dark") + "\n  }\n}",
  ""
].join("\n\n").trimEnd()+"\n";
const target = resolve(root, "packages/ui/src/tokens.css");
const mockup = resolve(root, "docs/design/mockups/tokens.css");
if (process.argv.includes("--check")) {
  assert.equal(readFileSync(target, "utf8"), css, "Generated UI tokens are stale");
  if (existsSync(mockup)) assert.equal(readFileSync(mockup, "utf8"), css, "Local mockup tokens are stale");
} else {
  writeFileSync(target, css);
  if (existsSync(resolve(root, "docs/design/mockups"))) writeFileSync(mockup, css);
}
function luminance(hex) {
  const values = hex.slice(1).match(/../g).map(value => parseInt(value,16)/255)
    .map(value => value <= .04045 ? value/12.92 : ((value+.055)/1.055)**2.4);
  return values[0]*.2126 + values[1]*.7152 + values[2]*.0722;
}
function contrast(a,b) {
  const x=luminance(a),y=luminance(b);
  return (Math.max(x,y)+.05)/(Math.min(x,y)+.05);
}
for (const [theme, values] of Object.entries(tokens.themes)) {
  const textPairs = [
    ["fg.primary","bg.surface"],["fg.secondary","bg.surface"],
    ["fg.secondary","bg.canvas"],["action.onPrimary","action.primary"],
    ["accent.fg","accent.bg"],["positive.fg","positive.bg"],
    ["warning.fg","warning.bg"],["critical.fg","critical.bg"]
  ];
  for(const [fg,bg] of textPairs) assert.ok(contrast(values[fg],values[bg])>=4.5,theme+" "+fg+"/"+bg+" contrast failed");
  for(const bg of ["bg.surface","bg.canvas"]) assert.ok(contrast(values["stroke.control"],values[bg])>=3,theme+" control contrast failed");
}
console.log("UI tokens synchronized; text and control contrast pairs passed.");
