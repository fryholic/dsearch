import { readFileSync, writeFileSync, existsSync } from "node:fs";
import { resolve } from "node:path";
import assert from "node:assert/strict";

const root = resolve(import.meta.dirname, "..");
const tokens = JSON.parse(readFileSync(resolve(root, "packages/ui/src/tokens.json"), "utf8"));
const name = key => key.replace(/[A-Z]/g, char => "-" + char.toLowerCase()).replaceAll(".", "-");
const colors = values => Object.entries(values).map(([key, value]) => "  --" + name(key) + ": " + value + ";").join("\n");
const appearances = Object.keys(tokens.appearances);
const valuesFor = (appearance, theme) => ({ ...tokens.themes[theme], ...tokens.appearances[appearance].themes[theme] });
const rule = (selector, values, scheme) => selector + " {\n" + (scheme ? "  color-scheme: " + scheme + ";\n" : "") + colors(values) + "\n}";
const common = [
  ...Object.entries(tokens.palette).map(([key, value]) => "  --palette-" + key + ": " + value + ";"),
  ...tokens.spacing.map(value => "  --space-" + value + ": " + value + "px;"),
  ...Object.entries(tokens.radius).map(([key, value]) => "  --radius-" + key + ": " + value + "px;"),
  ...Object.entries(tokens.typography).flatMap(([key, value]) => [
    "  --font-" + key + "-size: " + value.size + "px;",
    "  --font-" + key + "-line: " + value.lineHeight + "px;",
    "  --font-" + key + "-weight: " + value.weight + ";"
  ]),
  '  --font-family: system-ui, -apple-system, BlinkMacSystemFont, "Apple SD Gothic Neo", "Noto Sans KR", sans-serif;'
].join("\n");
const css = [
  "/* Generated by scripts/build-tokens.mjs. Edit tokens.json. */",
  ":root {\n  color-scheme: light;\n" + common + "\n" + colors(tokens.themes.light) + "\n}",
  ...appearances.filter(id => id !== tokens.defaultAppearance).map(id => rule(':root[data-appearance="' + id + '"]', valuesFor(id, "light"), "light")),
  ...appearances.map(id => rule('[data-palette-preview="' + id + '"]', valuesFor(id, "light"))),
  rule(':root[data-theme="dark"]', tokens.themes.dark, "dark"),
  ...appearances.filter(id => id !== tokens.defaultAppearance).map(id => rule(':root[data-theme="dark"][data-appearance="' + id + '"]', valuesFor(id, "dark"), "dark")),
  ...appearances.map(id => rule(':root[data-theme="dark"] [data-palette-preview="' + id + '"]', valuesFor(id, "dark"))),
  '@media (prefers-color-scheme: dark) {\n' + [
    rule(':root:not([data-theme="light"]):not([data-theme="dark"])', tokens.themes.dark, "dark"),
    ...appearances.filter(id => id !== tokens.defaultAppearance).map(id => rule(':root[data-appearance="' + id + '"]:not([data-theme="light"]):not([data-theme="dark"])', valuesFor(id, "dark"), "dark")),
    ...appearances.map(id => rule(':root:not([data-theme="light"]):not([data-theme="dark"]) [data-palette-preview="' + id + '"]', valuesFor(id, "dark")))
  ].join("\n\n") + '\n}',
  ""
].join("\n\n").trimEnd()+"\n";
const target = resolve(root, "packages/ui/src/tokens.css");
const mockup = resolve(root, "docs/design/mockups/tokens.css");
if (process.argv.includes("--check")) {
  assert.equal(readFileSync(target, "utf8"), css, "Generated UI tokens are stale");
  if (existsSync(mockup)) assert.equal(readFileSync(mockup, "utf8"), css, "Local mockup tokens are stale");
} else {
  writeFileSync(target, css);
  if (existsSync(resolve(root, "docs/design/mockups"))) writeFileSync(mockup, css);
}
function luminance(hex) {
  const values = hex.slice(1).match(/../g).map(value => parseInt(value,16)/255)
    .map(value => value <= .04045 ? value/12.92 : ((value+.055)/1.055)**2.4);
  return values[0]*.2126 + values[1]*.7152 + values[2]*.0722;
}
function contrast(a,b) {
  const x=luminance(a),y=luminance(b);
  return (Math.max(x,y)+.05)/(Math.min(x,y)+.05);
}
let minimumText = Infinity;
for (const appearance of appearances) for (const theme of ["light", "dark"]) {
  const values = valuesFor(appearance, theme);
  for (const value of Object.values(values)) assert.match(value, /^#[0-9A-F]{6}$/);
  if (theme === "light") for (const surface of ["bg.canvas", "bg.surface", "bg.subtle", "nav.bg", "nav.hover", "nav.selectedBg", "result.selectedBg", "evidence.bg", "action.soft", "accent.bg", "positive.bg", "warning.bg", "critical.bg"]) {
    assert.equal(values[surface], "#FFFFFF", appearance + " " + surface + " must remain white");
  }
  const textPairs = [
    ["fg.primary","bg.surface"],["fg.secondary","bg.surface"],
    ["fg.primary","bg.canvas"],["fg.secondary","bg.canvas"],
    ["fg.secondary","bg.subtle"],["action.onPrimary","action.primary"],
    ["action.fg","bg.surface"],["action.fg","bg.canvas"],
    ["action.fg","action.soft"],
    ["accent.fg","accent.bg"],["accent.fg","bg.canvas"],["positive.fg","positive.bg"],
    ["warning.fg","warning.bg"],["critical.fg","critical.bg"],
    ["nav.fg","nav.bg"],["nav.secondary","nav.bg"],
    ["nav.fg","nav.hover"],["nav.secondary","nav.hover"],
    ["nav.selectedFg","nav.selectedBg"],["nav.brandFg","nav.brandBg"],
    ["evidence.fg","evidence.bg"],["evidence.label","evidence.bg"],
    ["fg.primary","result.selectedBg"],["fg.secondary","result.selectedBg"]
  ];
  for(const [fg,bg] of textPairs) {
    const ratio = contrast(values[fg],values[bg]);
    minimumText = Math.min(minimumText, ratio);
    assert.ok(ratio >= 4.5, appearance+" "+theme+" "+fg+"/"+bg+" contrast failed: "+ratio);
  }
  for(const bg of ["bg.surface","bg.canvas"]) for (const fg of ["stroke.control", "focus.ring", "selection.stroke"]) {
    assert.ok(contrast(values[fg],values[bg]) >= 3, appearance+" "+theme+" "+fg+"/"+bg+" control contrast failed");
  }
}
console.log("UI tokens synchronized: 3 appearances × 2 themes; minimum tested text contrast " + minimumText.toFixed(2) + ":1. Control and focus contrast passed.");
